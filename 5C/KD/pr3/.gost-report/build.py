r.text(
    "Вайрфрейм первого экрана собран в Figma на фрейме десктопной ширины "
    "с модульной сеткой в 12 колонок. Шапка содержит логотип, меню из "
    "пяти пунктов и две кнопки, основной блок содержит заголовок, "
    "подзаголовок, строку поиска, две целевые кнопки и строку доверия, "
    "графику справа заменяет геометрическая фигура."
)
f2 = r.figure(
    "лендинг с направляющими.png",
    "Вайрфрейм первого экрана лендинга с направляющими модульной сетки",
)
