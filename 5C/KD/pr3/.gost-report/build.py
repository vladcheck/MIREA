    TitleConfig(
        work_type="Практическая работа",
        work_number="№3",
        discipline="Компьютерный дизайн",
        department="Кафедра компьютерного дизайна",
        topic="Информационная архитектура и вайрфрейм первого экрана лендинга, редизайн сайта mathprofi.ru",
        student_name="Валекжанин Владимир Сергеевич",
        student_group="ЭФБО-04-24",
        teacher_name="Мочалова Любовь Вадимовна",
        teacher_position="старший преподаватель",
        teacher_label="Проверил",
        year="2026",
    ),
    profile=MIREA_PROFILE,
