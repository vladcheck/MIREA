r.h1("Введение", center=True)
r.text(
    "Цель работы: построить информационную архитектуру лендинга "
    "образовательного ресурса mathprofi.ru и разработать вайрфрейм "
    "первого экрана десктопной версии."
)
r.text(
    "Архитектура описывает разделы лендинга в виде иерархического дерева "
    "и задает состав первого экрана, каталога тем, услуг, отзывов и "
    "всплывающих окон."
)

r.h1("1 Выполнение работы")
r.text(
    "Информационная архитектура собрана по иерархической модели. Корнем "
    "дерева выступает одна страница лендинга, первый уровень задают "
    "разделы шапки, оффера, каталога тем, услуг, отзывов, сведений об "
    "авторе, контактов и всплывающих окон, второй уровень раскрывает их "
    "содержимое, третий уровень описывает страницу урока."
)
