def set_run_font(run, name=FONT, size=14, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    # Корректная работа с кириллицей (w:rFonts w:cs / w:eastAsia)
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), name)


def add_par(
    doc,
    text="",
    align=WD_ALIGN_PARAGRAPH.JUSTIFY,
    indent=True,
    bold=False,
    italic=False,
    size=14,
    spacing=1.5,
    space_before=0,
    space_after=0,
):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = spacing
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    if indent:
        pf.first_line_indent = Mm(12.5)
    if text:
        run = p.add_run(text)
        set_run_font(run, size=size, bold=bold, italic=italic)
    return p


def add_heading1(doc, text):
    """Заголовок раздела: прописными, по центру, полужирный, без отступа."""
    p = add_par(
        doc,
        text.upper(),
        align=WD_ALIGN_PARAGRAPH.CENTER,
        indent=False,
        bold=True,
        space_before=12,
        space_after=12,
    )
    p.style = doc.styles["Heading 1"]
    for run in p.runs:
        set_run_font(run, size=14, bold=True)
    return p


def add_caption(doc, text, above=False):
    """Подпись рисунка (под рисунком) или листинга (над листингом)."""
    return add_par(
        doc,
        text,
        align=WD_ALIGN_PARAGRAPH.CENTER,
        indent=False,
        space_before=6 if above else 6,
        space_after=6 if not above else 6,
    )


def add_figure_or_placeholder(doc, image_entry):
    """Реальная картинка либо рамка-заглушка (см. PLACEHOLDER_IMAGES)."""
    path = BASE / image_entry["path"]
    if PLACEHOLDER_IMAGES or not path.exists():
        add_placeholder(
            doc,
            "[МЕСТО ДЛЯ РИСУНКА: {caption} — {path}]".format(
                caption=image_entry["caption"], path=image_entry["path"]
            ),
        )
    else:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(6)
        run = p.add_run()
        run.add_picture(str(path), width=Cm(image_entry["width_cm"]))
    add_caption(doc, image_entry["caption"])


def add_placeholder(doc, text):
    """Заметная рамка-заглушка для будущего изображения (центрированная)."""
    p = add_par(
        doc,
        text,
        align=WD_ALIGN_PARAGRAPH.CENTER,
        indent=False,
        bold=True,
        space_before=12,
        space_after=12,
    )
    ppr = p._p.get_or_add_pPr()
    borders = OxmlElement("w:pBdr")
    for side in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "8")
        el.set(qn("w:space"), "6")
        el.set(qn("w:color"), "auto")
        borders.append(el)
    ppr.append(borders)
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), "D9D9D9")
    ppr.append(shd)
    return p


def add_listing(doc, source_path, caption):
    add_caption(doc, caption, above=True)
    text = source_path.read_text(encoding="utf-8").rstrip("\n")
    for line in text.split("\n"):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        pf = p.paragraph_format
        pf.line_spacing = 1.0
        pf.space_before = Pt(0)
        pf.space_after = Pt(0)
        run = p.add_run(line if line else " ")
        set_run_font(run, name=CODE_FONT, size=10)


def add_page_number_footer(section):
    """Номер страницы внизу по центру (поле PAGE через сырой XML)."""
    section.footer.is_linked_to_previous = False
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    set_run_font(run, size=12)
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_end)


def force_update_fields(doc):
    settings = doc.settings.element
    upd = settings.find(qn("w:updateFields"))
    if upd is None:
        upd = OxmlElement("w:updateFields")
        settings.append(upd)
    upd.set(qn("w:val"), "true")


