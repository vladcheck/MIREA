def placeholder_box(text):
    """Серая рамка-заглушка вместо рисунка (по инструкции — до появления
    реальных изображений)."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    for side in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "12")
        el.set(qn("w:space"), "6")
        el.set(qn("w:color"), "808080")
        pBdr.append(el)
    pPr.append(pBdr)
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), "E7E6E6")
    pPr.append(shd)
    r = p.add_run("[МЕСТО ДЛЯ РИСУНКА]\n" + text + "\n[КОНЕЦ ЗАГЛУШКИ]")
    r.font.name = TNR
    r.font.size = Pt(12)
    r.font.bold = True
    r.font.color.rgb = GREY
    return p


def add_image(idx):
    """Вставка изображения по индексу IMAGES либо заглушки."""
    rel_path, cap, width = IMAGES[idx]
    img_path = ROOT / rel_path
