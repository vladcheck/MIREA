#include <avr/io.h>
#include <stdint.h>

// Лабораторная работа №4, задача 4, подпункт г (вариант 4): элемент 4ИЛИ.
// Входы PA0-PA3 (кнопки замыкают на GND, включены подтяжки, нажатая
// кнопка читается как 0, поэтому входы программно инвертируются).
// Выход PD0 (светодиод, активная единица): Y равен A+B+C+D.
// Таблица: Y равен 0 только при всех отпущенных кнопках, иначе Y равен 1.

int main(void)
{
    DDRA = 0x00;  // порт A на вход
    PORTA = 0xFF; // подтяжки входов
    DDRD |= 0x01; // бит 0 порта D на выход
    while (1)
    {
        uint8_t a = (uint8_t)(~PINA & 0x0F); // нажатые кнопки как единицы
        if (a != 0)
            PORTD |= 0x01; // хотя бы один вход равен 1
        else
            PORTD &= (uint8_t)~0x01; // все входы равны 0
    }
}
