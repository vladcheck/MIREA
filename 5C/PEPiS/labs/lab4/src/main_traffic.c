#include <avr/io.h>
#include <util/delay.h>

// Лабораторная работа №4, задача 12, светофор.
// Выход PD1 (красный) включен 3 с, выход PD2 (желтый) включен 1 с,
// выход PD3 (зеленый) горит 3 с, затем цикл повторяется.
// Частота тактирования 8 МГц задана символом F_CPU в platformio.ini,
// задержки реализованы функциями avr-libc.

int main(void)
{
    DDRD |= 0x0E;   // биты 1-3 порта D на выход
    PORTD &= 0xF1;  // все три светодиода погашены
    while (1)
    {
        PORTD |= 0x02;   // красный
        _delay_ms(3000);
        PORTD &= 0xF1;
        PORTD |= 0x04;   // желтый
        _delay_ms(1000);
        PORTD &= 0xF1;
        PORTD |= 0x08;   // зеленый
        _delay_ms(3000);
        PORTD &= 0xF1;
    }
}
