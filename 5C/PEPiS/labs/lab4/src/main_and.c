#include <avr/io.h>
#include <stdint.h>

// Лабораторная работа №4, задача 8, подпункт г (вариант 4).
// Два двоичных четырехразрядных числа задаются битами PA0-PA3 и PB0-PB3
// (тумблеры, замкнутый дает единицу). В порт D выводится поразрядная
// конъюнкция тетрад: OUT равен (A и B) по каждому из четырех битов.
// Остальные подпункты: а) сумма, б) произведение, в) поразрядное ИЛИ.

int main(void)
{
    DDRA = 0x00;  // порты A и B на вход
    DDRB = 0x00;
    PORTA = 0x00; // без подтяжек, уровни задают тумблеры
    PORTB = 0x00;
    DDRD = 0xFF;  // порт D на выход
    while (1)
    {
        uint8_t a = (uint8_t)(PINA & 0x0F);
        uint8_t b = (uint8_t)(PINB & 0x0F);
        PORTD = (uint8_t)(a & b); // поразрядная конъюнкция
    }
}
