#include <avr/io.h>
#include <avr/interrupt.h>

// Лабораторная работа №4 (стенд МПСУ-Ш-МН, ATmega32), учебный пример 1.
// Порт A работает на вход с включенными подтяжками, порт D на выход.
// Бит PA2 управляет портом D: PA2 равен 1, на выходе 0xF0,
// иначе на выходе 0x0F.
// Примечание: в методичке программа приведена для компилятора ImageCraft
// (заголовок iom32v.h, макросы CLI/SEI, void main). Здесь тот же алгоритм
// записан для avr-gcc (заголовки avr/io.h, avr/interrupt.h, int main).

void port_init(void)
{
    PORTA = 0xFF; // включить подтяжки порта A
    DDRA = 0x00;  // порт A на вход
    PORTD = 0x00; // нулевое значение в порт D
    DDRD = 0xFF;  // порт D на выход
}

void init_devices(void)
{
    cli();        // запретить прерывания на время настройки
    port_init();  // настроить порты
    MCUCR = 0x00; // внешние прерывания не используются
    GICR = 0x00;
    TIMSK = 0x00; // прерывания таймеров не используются
    sei();        // разрешить прерывания
}

int main(void)
{
    init_devices();
    while (1)
    {
        if ((PINA & 0x04) != 0) // бит 2 входа PA отличен от нуля
            PORTD = 0xF0;       // PORTD равно 1111 0000
        else
            PORTD = 0x0F;       // иначе PORTD равно 0000 1111
    }
}
