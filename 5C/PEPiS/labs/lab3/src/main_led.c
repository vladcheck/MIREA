#include "stm32f4xx.h"

// Лабораторная работа №3, пример из п. 2.2 методички (трек STM32F407).
// Свитч на PB8 (замыкание на GND), светодиод на PA0.
// PB8 настроен как вход с внутренней подтяжкой вверх:
// отпущенный свитч читается как 1, замкнутый как 0 (активный низкий).
// Замкнутый свитч зажигает светодиод, разомкнутый гасит.

int main(void)
{
    // 1. Включаем тактирование портов A и B (шина AHB1)
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN | RCC_AHB1ENR_GPIOBEN;
    volatile uint32_t tmp = RCC->AHB1ENR;
    (void)tmp; // дождаться стабилизации тактов перед обращением к GPIO

    // 2. PB8 как вход с подтяжкой вверх: MODER = 00 (вход), PUPDR = 01 (pull-up)
    GPIOB->MODER &= ~(0x3U << (8 * 2));
    GPIOB->PUPDR &= ~(0x3U << (8 * 2));
    GPIOB->PUPDR |= (0x1U << (8 * 2));

    // 3. PA0 как выход push-pull, низкая скорость, без подтяжек
    GPIOA->MODER &= ~(0x3U << (0 * 2));
    GPIOA->MODER |= (0x1U << (0 * 2)); // 01 выход
    GPIOA->OTYPER &= ~(1U << 0);       // push-pull
    GPIOA->OSPEEDR &= ~(0x3U << (0 * 2));
    GPIOA->PUPDR &= ~(0x3U << (0 * 2));

    // 4. Основной цикл: низкий уровень на PB8 включает LED, высокий гасит
    while (1)
    {
        if ((GPIOB->IDR & (1U << 8)) == 0)
            GPIOA->BSRR = (1U << 0);        // включить светодиод
        else
            GPIOA->BSRR = (1U << (0 + 16)); // выключить светодиод
    }
}
