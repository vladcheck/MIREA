def para(
    text="",
    bold=False,
    align=WD_ALIGN_PARAGRAPH.JUSTIFY,
    size=14,
    font=TNR,
    color=None,
    space_after=0,
):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(text)
    r.font.name = font
    r.font.size = Pt(size)
    r.font.bold = bold
    if color:
        r.font.color.rgb = color
    return p


def heading(text):
    p = doc.add_paragraph(style="Heading 1")
    p.add_run(text)
    return p


def caption(text):
    return para(text, align=WD_ALIGN_PARAGRAPH.CENTER)


def code_block(lines):
    """Вставка листинга: Consolas 10, одинарный интервал, выравнивание влево."""
    for line in lines:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(line if line else " ")
        r.font.name = CONS
        r.font.size = Pt(10)


