/*====================================================================
 * Практическая работа № 5 «Отображение информации в
 * микроконтроллерных системах» (пр9-10, Proteus),
 * УЧЕБНЫЙ ПРИМЕР — воспроизведение листинга 9.13 методички:
 * статический вывод цифры 5 на семисегментный индикатор с общим
 * катодом, подключённый к PA0–PA7 STM32F103C8.
 *
 * Подключение (табл. 9.22 методички):
 *   сегменты a–dp — к PA0–PA7 через токоограничивающие резисторы
 *   330 Ом (расчёт: (3,3 В − 2,0 В) / 4 мА = 325 Ом -> 330 Ом);
 *   общий катод индикатора — к GND.
 *
 * Тактирование: HSI 8 МГц без PLL (как в базовой конфигурации
 * практикума). Значение 0x22222222 в GPIOA->CRL задаёт для каждого
 * вывода PA0–PA7 сочетание MODE = 10, CNF = 00 — выход общего
 * назначения push-pull с частотой переключения до 2 МГц. Запись в
 * BSRR изменяет состояние восьми линий одной операцией: младшие
 * 16 бит устанавливают выбранные линии, старшие 16 бит сбрасывают
 * остальные (нет операции чтение–изменение–запись над ODR).
 *
 * Сборка: PlatformIO с фреймворком CMSIS (см. platformio.ini).
 * Результат (.elf/.hex) указывается в поле Program File модели
 * STM32F103C8 в Proteus 8.17.
 *====================================================================*/
#include "stm32f1xx.h"
#include <stdint.h>

#define DISPLAY_COMMON_ANODE 0U

/* Таблица кодов цифр для индикатора с ОБЩИМ КАТОДОМ:
 * младший бит — сегмент a, бит 6 — сегмент g, бит 7 — десятичная
 * точка dp (для цифр 0–9 равна нулю). Единица включает сегмент. */
static const uint8_t segment_code_cc[10] = {
    0x3FU, 0x06U, 0x5BU, 0x4FU, 0x66U,
    0x6DU, 0x7DU, 0x07U, 0x7FU, 0x6FU
};

static void Display_Init(void)
{
    RCC->APB2ENR |= RCC_APB2ENR_IOPAEN;

    /* PA0–PA7: выход push-pull, частота до 2 МГц. */
    GPIOA->CRL = 0x22222222U;

    /* Начальное состояние всех линий — низкий уровень. */
    GPIOA->BSRR = 0x00FF0000U;
}

static void Display_WriteCode(uint8_t code)
{
    uint32_t set_mask = (uint32_t)code;
    uint32_t reset_mask = ((uint32_t)(~code) & 0xFFU) << 16;

    GPIOA->BSRR = reset_mask | set_mask;
}

static void Display_Digit(uint8_t digit)
{
    uint8_t code = 0U;

    if (digit < 10U) {
        code = segment_code_cc[digit];
    }

#if DISPLAY_COMMON_ANODE
    /* Для общего анода рисунок цифры требует инверсии кода
     * в пределах восьми младших битов (например, 0 -> 0xC0). */
    code = (uint8_t)(~code);
#endif

    Display_WriteCode(code);
}

int main(void)
{
    Display_Init();
    Display_Digit(5U);

    while (1) {
        /* Статическая индикация не требует повторной записи. */
    }
}
