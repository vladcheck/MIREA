/*====================================================================
 * Практическая работа № 15-16 «Исследование широтно-импульсной
 * модуляции, реализованной микроконтроллером МК-52»,
 * ИНДИВИДУАЛЬНЫЙ ВАРИАНТ 4 (таблица 19 методички):
 *   период следования импульсов T = 0,06 с;
 *   скважность Q = 75 %;
 *   тактовая частота кварца Fosc = 13 МГц.
 *
 * Структура программы совпадает с учебным примером (режим
 * автоперезагрузки таймера Т/С2, ШИМ на выводе P1.0), меняются
 * только расчётные константы.
 *
 * Расчёт по формулам (3) и (4) методички:
 *   C = Fosc/12 = 13 000 000/12 = 1 083 333,33 Гц;
 *   R = 65536 - C*T = 65536 - 1 083 333,33*0,06 = 65536 - 65 000
 *     = 536 = 0x0218;
 *   RCAP2H = 0x02, RCAP2L = 0x18;
 *   период таймера T = (65536 - 536)/C = 65 000/1 083 333,33
 *     = 0,0600 с;
 *   tmpCnt = Q*(65536 - R) = 0,75*65 000 = 48 750 = 0xBE6E;
 *   длительность высокого уровня
 *     t = tmpCnt/C = 48 750/1 083 333,33 = 0,0450 с;
 *   контроль: Q = t/T = 0,0450/0,0600 = 75 %.
 *
 * Сборка прошивки: pio run -e pr1516_variant4 (см. platformio.ini).
 *====================================================================*/
#include <8052.h>

#ifdef __SDCC
#define T2_ISR __interrupt(5) __using(2)
#define MAIN_RET void /* SDCC для MCS-51 допускает void main(void) */
#else
/* Заглушка для clang -fsyntax-only: без атрибутов прерывания. */
#define T2_ISR
#define MAIN_RET int
#endif

/* Расчётные константы варианта 4 (подробный вывод в шапке файла). */
#define RCAP2H_VALUE 0x02   /* старший байт R = 536 = 0x0218 */
#define RCAP2L_VALUE 0x18   /* младший байт R               */
#define TMP_CNT      48750U /* Q*(65536 - R) = 0,75*65 000  */

static volatile unsigned int cnt;    /* переменная цикла обработчика */
static volatile unsigned int tmpCnt; /* переменная, определяющая скважность */

/* Обработчик прерывания таймера 2: формирует один импульс ШИМ. */
void t2_isr(void) T2_ISR
{
    TF2 = 0;          /* очистка флага переполнения таймера 2 */
    cnt = tmpCnt;     /* скважность задаётся переменной tmpCnt */
    P1_0 = 1;         /* фронт импульса на выводе P1.0 */
    while (cnt != 0) {
        cnt--;
    }
    P1_0 = 0;         /* спад импульса на выводе P1.0 */
}

MAIN_RET main(void)
{
    tmpCnt = TMP_CNT; /* скважность 75 % при T = 0,06 с */

    P1_0 = 0;         /* исходный низкий уровень на P1.0 */
    /* Регистр перезагрузки таймера 2: R = 0x0218, период 0,06 с. */
    RCAP2H = RCAP2H_VALUE;
    RCAP2L = RCAP2L_VALUE;
    TL2 = RCAP2L_VALUE; /* счётчик стартует из точки перезагрузки */
    TH2 = RCAP2H_VALUE;

    /* Режим таймера 2: 16-разрядный таймер с автоперезагрузкой. */
    CP_RL2 = 0;       /* автоперезагрузка, не захват */
    C_T2 = 0;         /* интервальный таймер, не счётчик */
    RCLK = 0;         /* синхронизация UART не используется */
    TCLK = 0;
    EXEN2 = 0;        /* перепады на T2EX игнорируются */

    ET2 = 1;          /* разрешение прерывания от Т/С2 (IE.5) */
    EA = 1;           /* глобальное разрешение прерываний */

    TR2 = 1;          /* запуск таймера 2 */

    while (1) {
        /* основной цикл пуст: вся работа в обработчике прерывания */
    }
}
