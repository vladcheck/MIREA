/*====================================================================
 * Практическая работа № 15-16 «Исследование широтно-импульсной
 * модуляции, реализованной микроконтроллером МК-52»,
 * УЧЕБНЫЙ ПРИМЕР: воспроизведение программы раздела 2 методички
 * (режим автоперезагрузки таймера Т/С2, ШИМ на выводе P1.0).
 *
 * Целевая платформа: МК-52 (8052-совместимый, Intel MCS-51),
 * компилятор SDCC (PlatformIO, platform = intel_mcs51). Для SDCC
 * подключается родной заголовок <8052.h> с объявлениями __sfr/__sbit;
 * для проверки синтаксиса компилятором clang используется заглушка
 * tools/include/8052.h (переменные volatile, адресация не нужна).
 *
 * Параметры учебного примера (кварц 11,0592 МГц):
 *   C  = Fosc/12 = 11 059 200/12 = 921 600 Гц (машинный цикл);
 *   RCAP2H = RCAP2L = 0x00 -> период таймера
 *        T = (65536 - 0)/C = 65536/921600 = 71,1 мс;
 *   скважность задаётся переменной tmpCnt = 4000 (см. формулу (4)
 *   методички): Q = tmpCnt/(65536 - R) = 4000/65536 = 6,1 %;
 *   длительность высокого уровня t = Q*T = 4000/921600 = 4,34 мс.
 *
 * Примечание. Согласно формуле (4) методички, один отсчёт цикла
 * «while (cnt != 0) cnt--;» принимается равным одному машинному
 * циклу. На кристалле 8051 команда DJNZ занимает два машинных цикла,
 * поэтому физическая скважность получится вдвое больше расчётной;
 * здесь сохранена расчётная модель методички, как и требуется в
 * задании на моделирование.
 *
 * Сборка прошивки: pio run -e pr1516_example (см. platformio.ini).
 *====================================================================*/
#include <8052.h>

#ifdef __SDCC
/* Вектор прерывания 5 соответствует TF2/EXF2 таймера 2 МК-52,
 * регистровый банк 2 выбирается так же, как директива bank2
 * в листинге методички. */
#define T2_ISR __interrupt(5) __using(2)
#define MAIN_RET void /* SDCC для MCS-51 допускает void main(void) */
#else
/* Заглушка для clang -fsyntax-only: без атрибутов прерывания. */
#define T2_ISR
#define MAIN_RET int
#endif

static volatile unsigned int cnt;    /* переменная цикла обработчика */
static volatile unsigned int tmpCnt; /* переменная, определяющая скважность */

/* Обработчик прерывания таймера 2: формирует один импульс ШИМ.
 * Фронт импульса (P1.0 = 1) ставится сразу, спад (P1.0 = 0) по
 * окончании программной задержки длительностью tmpCnt машинных
 * циклов (формула (4) методички). */
void t2_isr(void) T2_ISR
{
    TF2 = 0;          /* очистка флага переполнения таймера 2 */
    cnt = tmpCnt;     /* скважность задаётся переменной tmpCnt из main */
    P1_0 = 1;         /* фронт импульса на выводе P1.0 */
    while (cnt != 0) {
        cnt--;
    }
    P1_0 = 0;         /* спад импульса на выводе P1.0 */
}

MAIN_RET main(void)
{
    tmpCnt = 4000;    /* скважность импульсов учебного примера */

    P1_0 = 0;         /* исходный низкий уровень на P1.0 */
    /* Регистр перезагрузки таймера 2: R = 0x0000, период 71,1 мс. */
    RCAP2H = 0x00;    /* старший байт величины перезагрузки */
    RCAP2L = 0x00;    /* младший байт величины перезагрузки */
    TL2 = 0x00;       /* стартовое значение счётчика */
    TH2 = 0x00;

    /* Режим таймера 2: 16-разрядный таймер с автоперезагрузкой.
     * Действия над T2CON повторяют листинг методички:
     * T2CON &= 0xFC сбрасывает CP/RL2 (бит 0) и C/T2 (бит 1). */
    CP_RL2 = 0;       /* автоперезагрузка, не захват */
    C_T2 = 0;         /* интервальный таймер, не счётчик */
    RCLK = 0;         /* синхронизация UART не используется */
    TCLK = 0;
    EXEN2 = 0;        /* перепады на T2EX игнорируются */

    ET2 = 1;          /* разрешение прерывания от Т/С2 (IE.5) */
    EA = 1;           /* глобальное разрешение прерываний */

    TR2 = 1;          /* запуск таймера 2 (T2CON |= 0x04) */

    while (1) {
        /* основной цикл пуст: вся работа в обработчике прерывания */
    }
}
