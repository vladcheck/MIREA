# ---------------------------------------------------------------------------
# Квантователь и ЦАП
# ---------------------------------------------------------------------------
def quantize(u_in, vref_p, vref_m, bits):
    """Выходной код АЦП: trunc((u_in - Vref-) / (Vref+ - Vref-) * 2**bits),
    ограниченный диапазоном 0 ... 2**bits - 1."""
    levels = 1 << bits
    span = vref_p - vref_m
    if span <= 0.0:
        raise ValueError("Vref+ должен быть больше Vref-")
    code = floor((u_in - vref_m) / span * levels)
    return max(0, min(levels - 1, int(code)))


def dac_voltage(code, vref_p, vref_m, bits):
    """Напряжение на выходе виртуального ЦАП для кода (идеальная шкала)."""
    levels = 1 << bits
    return vref_m + code * (vref_p - vref_m) / levels


def code_direct(u_in, vref_p, vref_m, bits):
    """Расчётный код по формуле (1) методички: Dрасч = 2**k * uвх / (Vref+ - Vref-).
    Для разнополярного опорного напряжения методичка использует модуль Vref-."""
    levels = 1 << bits
    return levels * u_in / (vref_p + abs(vref_m))


def lsb_voltage(vref_p, vref_m, bits):
    """Цена младшего разряда, В."""
    return (vref_p - vref_m) / (1 << bits)


# ---------------------------------------------------------------------------
# Таблица исследования точности (таблица 17 методички)
# ---------------------------------------------------------------------------
def investigation_table(u_inputs, vref_p, vref_m, bits):
    """Строки таблицы вида 17: uвх, uвых(ЦАП), D(2), D(16), D, Dрасч, dU, %.

    Для однополярного опорного напряжения код прямой (без инверсии),
    для разнополярного добавляется столбец Dинв по конвенции методички."""
    bipolar = vref_m < 0.0
    rows = []
    for u in u_inputs:
        code = quantize(u, vref_p, vref_m, bits)
        u_dac = dac_voltage(code, vref_p, vref_m, bits)
        d_calc = code_direct(u, vref_p, vref_m, bits)
        d_u = 100.0 * (u_dac - u) / u if u != 0.0 else 0.0
        row = {
            "u_in": u,
            "u_dac": round(u_dac, 6),
            "code_bin": format(code, "0{}b".format(bits)),
            "code_hex": format(code, "0{}X".format(bits // 4)),
            "code_dec": code,
            "d_calc": round(d_calc, 2),
            "d_u_pct": round(d_u, 2),
        }
        if bipolar:
            # Конвенция методички: на пробниках — смещённый код,
            # прямой код получается вычитанием 128 (формула 2).
            d_off = quantize(u, vref_p, vref_m, bits)
            row["code_probe"] = d_off
            row["code_dec"] = d_off - (1 << (bits - 1))
        rows.append(row)
    return rows


