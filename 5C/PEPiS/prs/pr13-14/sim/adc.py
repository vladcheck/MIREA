"""Битово-точная модель виртуальных АЦП/ЦАП Multisim (практика 13-14).

Воспроизводит поведение виртуального АЦП из задания 1 методички
(рис. 58): линейное квантование входного напряжения между опорными
уровнями Vref- ... Vref+ с округлением кода вниз (trunc), виртуальный
ЦАП — обратное восстановление напряжения по коду. Для разнополярного
опорного напряжения методичка фиксирует «инверсный» код на пробниках;
для однополярного (вариант 4) код прямой.

Базовая конфигурация учебного примера (задание 2, рис. 60 методички):
8-разрядный АЦП, однополярное опорное напряжение Vref+ = +5 В,
Vref- = 0 В, uвх = +1 В -> код D = trunc(256 * 1 / 5) = 51
(совпадает с показанием пробников методички).

Конфигурация индивидуального варианта 4 (табл. 18 методички):
16-разрядный АЦП, Vref+ = +5 В, Vref- = 0 В, прямой код:
D = trunc(65536 * uвх / 5).
"""

