# Модель обмена «МК-51 — АЦП» (задание 2): шаги программы и пробники
# ---------------------------------------------------------------------------
def mcu_read_code(u_in, vref_p, vref_m, bits):
    """Эмуляция программы МК-51: запуск SOC, ожидание EOC, чтение кода.

    Возвращает словарь с кодом, байтами для портов и показаниями
    пробников (X0..X7 — младший байт, выведенный на P2;
    X8..X15 — старший байт, снятый с выходов АЦП)."""
    code = quantize(u_in, vref_p, vref_m, bits)
    low = code & 0xFF
    high = (code >> 8) & 0xFF
    probes = [((low >> i) & 1) for i in range(8)]
    probes += [((high >> i) & 1) for i in range(8)]
    return {
        "u_in": u_in,
        "code": code,
        "p2_low": low,      # младший байт на порту P2
        "p0_in": high,      # старший байт, прочитанный из P0
        "p1_in": low,       # младший байт, прочитанный из P1
        "probes": probes,   # X0..X15, 1 = пробник светится
    }


