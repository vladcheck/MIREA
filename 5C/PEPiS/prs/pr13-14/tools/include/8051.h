/* ============================================================================
 * Заглушка заголовочного файла <8051.h> для синтаксической проверки clang
 * (практика 13-14, целевой инструментальный компилятор — SDCC, у которого
 * есть собственный настоящий 8051.h с ключевыми словами sfr/sbit).
 *
 * Слова sfr/sbit языка C не знает, поэтому здесь они макро-подменяются
 * на «static volatile unsigned char» с инициализатором адреса. Для проверки
 * clang -fsyntax-only этого достаточно: типы совпадают с моделью SDCC
 * (8-разрядные регистры специальных функций и биты).
 *
 * ВНИМАНИЕ: этот файл НЕ предназначен для прошивки МК. Для сборки
 * используйте PlatformIO (платформа intel_mcs51, компилятор SDCC) —
 * см. platformio.ini; там подключается настоящий заголовок SDCC.
 * ==========================================================================*/
#ifndef STUB_8051_H
#define STUB_8051_H

/* Эмуляция ключевых слов SDCC: регистры специальных функций и биты. */
#define sfr  static volatile unsigned char
#define sbit static volatile unsigned char

/* Порты P0..P3 (адреса регистров по карте памяти MCS-51). */
sfr P0 = 0x80;
sfr P1 = 0x90;
sfr P2 = 0xA0;
sfr P3 = 0xB0;

/* Отдельно адресуемые биты порта P3, используемые в программах. */
sbit P36 = 0xB6; /* P3.6 — выход SOC («начать преобразование») АЦП */
sbit P37 = 0xB7; /* P3.7 — вход EOC («конец преобразования») АЦП     */

#endif /* STUB_8051_H */
