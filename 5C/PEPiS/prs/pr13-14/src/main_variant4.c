/*====================================================================
 * Практическое занятие 13-14 «Изучение принципов работы
 * аналого-цифровых преобразователей» (лабораторная работа № 7
 * методички), ИНДИВИДУАЛЬНЫЙ ВАРИАНТ 4 (табл. 18 методички):
 *
 *   - разрядность виртуального АЦП: 16 бит;
 *   - опорные напряжения: Vref+ = +5 В, Vref- = 0 В (однополярные).
 *
 * Задание 2 (рис. 60 методички, расширенная до 16 бит схема):
 *   - V2 = +5 В подключён к Vref+, вывод Vref- соединён с землёй
 *     (однополярный режим, цифровой код прямой, НЕ инверсный);
 *   - выходы D0…D7 АЦП подключены к порту P1 МК-51;
 *   - выходы D8…D15 АЦП подключены к порту P0 МК-51;
 *   - пробники Х0…Х7 сняты с линий D0…D7, Х8…Х15 — с линий D8…D15
 *     (код отображается прямо с выходов АЦП, как на рис. 58);
 *   - младший байт кода дополнительно дублируется на порт P2
 *     (как «включаем пробники» в учебном примере);
 *   - вывод P3.6 соединён с входом SOC («начать преобразование»);
 *   - вывод P3.7 соединён с выходом EOC («конец преобразования»),
 *     программа дожидается готовности кода перед чтением (перед
 *     чтением в линию P3.7 записывается 1 — типовой приём работы
 *     с квази-двунаправленными портами МК-51);
 *   - вход OE АЦП (активный ноль) соединён с общим проводом,
 *     поэтому цифровые выходы D0…D15 разрешены постоянно.
 *
 * Расчёт кода (формула 1 методички для 16-разрядного АЦП,
 * однополярное опорное напряжение):
 *   D = 65536 * uвх / (Vref+ - Vref-) = 65536 * uвх / 5.
 * Для контрольных точек задания 2:
 *   uвх = 1,0 В -> D = 13107; uвх = 2,5 В -> D = 32768;
 *   uвх = 4,0 В -> D = 52428 (округление вниз).
 *
 * Сборка: PlatformIO, платформа intel_mcs51 (SDCC) — см. platformio.ini.
 * Проверка синтаксиса: clang -fsyntax-only -Wall -Wextra -I tools/include.
 * «int main(void)» вместо «void main()» из методички — см. то же
 * пояснение в main_example.c.
 *=====================================================================*/
#include <8051.h> /* заголовочный файл регистров МК-51 */

/* Съём цифрового кода 16-разрядного АЦП виртуальной моделью МК-51.
 * Возвращает код D0…D15, полученный после одного преобразования. */
static unsigned int ADC_Read16(void)
{
    unsigned int val;

    P36 = 0; /* P3.6 — выход SOC: исходный уровень */
    P37 = 1; /* отпускаем линию P3.7: EOC работает на вход */
    P36 = 1; /* перепад 0 -> 1 на SOC: начать преобразование */

    while (P37 == 0) /* ожидание конца преобразования (EOC = 1) */
    {
    }

    val = (unsigned int)P1;          /* младший байт D0…D7 из P1  */
    val |= (unsigned int)P0 << 8;    /* старший байт D8…D15 из P0 */

    return val;
}

int main(void)
{
    unsigned int val; /* 16-разрядный цифровой код АЦП */

    P0 = 0xFF; /* инициализируем P0 на вход (код D8…D15 с АЦП) */
    P1 = 0xFF; /* инициализируем P1 на вход (код D0…D7 с АЦП)  */
    P2 = 0x00; /* инициализируем P2 на выход (дублирует D0…D7) */

    val = ADC_Read16();      /* запуск преобразования и чтение кода */
    P2 = (unsigned char)val; /* младший байт кода на P2 (пробники)  */

    while (1) /* бесконечный цикл: удержание результата */
    {
    }

    return 0; /* недостижимо: цикл удержания активен постоянно */
}
