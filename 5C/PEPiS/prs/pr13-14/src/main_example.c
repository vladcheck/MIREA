/*====================================================================
 * Практическое занятие 13-14 «Изучение принципов работы
 * аналого-цифровых преобразователей» (лабораторная работа № 7
 * методички), УЧЕБНЫЙ ПРИМЕР — воспроизведение листинга методички
 * (п. 2, задание 2, рис. 60): подключение МК-51 к 8-разрядному
 * виртуальному АЦП и съём цифрового кода пробниками.
 *
 * Схема (рис. 60 методички):
 *   - V1 = +1 В  — входное напряжение Vin АЦП (источник V3 по рис. 58);
 *   - V2 = +5 В  — опорное напряжение Vref+ (однополярное, Vref- = 0);
 *   - выходы D0…D7 АЦП подключены к порту P1 МК-51;
 *   - пробники Х0…Х7 подключены к порту P2;
 *   - вывод P3.6 МК соединён с входом SOC («начать преобразование»);
 *   - вход OE АЦП разрешает выходной код (активный ноль, в схеме
 *     подключён к инвертору 74LS04, как на рис. 58).
 *
 * Цифровой код однополярного 8-разрядного АЦП:
 *   D = 256 * uвх / (Vref+ - Vref-) = 256 * 1 / 5 = 51 (округление
 *   вниз), что и показывают пробники Х7…Х0 (00110011).
 *
 * Порядок работы программы:
 *   1) P1 инициализируется на вход (0xFF), P2 — на выход (0x00);
 *   2) P3.6 = 0, затем P3.6 = 1 — перепад запускает преобразование;
 *   3) код с выходов D0…D7 читается через P1 в переменную val;
 *   4) val выводится на P2 — загораются пробники;
 *   5) бесконечный цикл удерживает результат на индикации.
 *
 * Сборка: PlatformIO, платформа intel_mcs51 (SDCC) — см. platformio.ini.
 * Проверка синтаксиса: clang -fsyntax-only -Wall -Wextra -I tools/include
 * (в tools/include лежит заглушка 8051.h для clang, настоящий файл
 * подключает SDCC при сборке прошивки). Листинг методички оформлен как
 * «void main()»; здесь использован «int main(void)» — SDCC допускает
 * оба варианта, а clang -Wall -Wextra на void main выдаёт предупреждение.
 *====================================================================*/
#include <8051.h> /* заголовочный файл регистров МК-51 */

int main(void)
{
    unsigned char val; /* цифровой код, соответствующий uвх */

    P1 = 0xFF; /* инициализируем P1 на вход (код D0…D7 с АЦП) */
    P2 = 0x00; /* инициализируем P2 на выход (пробники Х0…Х7) */
    P36 = 0;   /* P3.6 — выход SOC */
    P36 = 1;   /* перепад 0 -> 1: начать преобразование */
    val = P1;  /* P1 содержит цифровой код АЦП */
    P2 = val;  /* выводим код на пробники */

    while (1) /* бесконечный цикл: удержание индикации */
    {
    }

    return 0; /* недостижимо: цикл удержания активен постоянно */
}
