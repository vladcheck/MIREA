#include <avr/io.h>
#include <util/delay.h>
#include <stdint.h>

// Лабораторная работа №4, задача 3, вариант 4.
// Зависимость выхода от входов PD2:PD1:
//   00 -> 0001 0000 (0x10), 01 -> 0010 0000 (0x20),
//   10 -> 0100 0000 (0x40), 11 -> 1000 0000 (0x80).
// Порт D используется и на вход, и на выход (примечание методички
// к вариантам 4, 8, 10): биты 1 и 2 входы с подтяжками, биты 4-7 выходы
// на светодиоды. Биты 0 и 3 входы с подтяжками, в задаче не участвуют.
// Кнопки замыкают входы на GND: нажата дает 0, отпущена дает 1.

static const uint8_t TABLE[4] = {0x10, 0x20, 0x40, 0x80};

int main(void)
{
    DDRD = 0xF0;  // биты 4-7 на выход, биты 0-3 на вход
    PORTD = 0x0F; // подтяжки входов, выходы пока нули
    while (1)
    {
        uint8_t sel = (uint8_t)((PIND >> 1) & 0x03);
        _delay_ms(5); // антидребезг
        if (sel != (uint8_t)((PIND >> 1) & 0x03))
            continue;
        PORTD = (uint8_t)(TABLE[sel] | 0x0F);
    }
}
