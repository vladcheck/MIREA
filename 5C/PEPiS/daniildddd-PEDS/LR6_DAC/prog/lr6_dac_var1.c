#include <8051.h>

// ЛР №6, Вариант 1: вывод кодов 8, 36, 107 в порт P1 на ЦАП (DA2).
// Плата: DD1 P8051AH, DA2 DAC08 (B0=LSB...B7=MSB), Uref=+5В.
// Uвых = D * 5 / 255: 8->0.157В, 36->0.706В, 107->2.098В.

void delay(unsigned int n)
{
    unsigned int j;
    for (j = 0; j < n; j++)
        continue; // пустой цикл: пауза для установления Uвых ЦАП
}

void main()
{
    // Массив входных кодов по варианту 1 (таблица 15 ТЗ)
    unsigned char var[3] = {8, 36, 107};
    unsigned char i, j;

    P1 = 0x00; // начальное состояние порта P1 (все нули)

    // По очереди выводим каждый код в порт P1
    for (i = 0; i < 3; i++)
    {
        P1 = var[i]; // код -> 8 линий P1.0-P1.7 -> входы B0-B7 ЦАП
                     // ЦАП преобразует код в напряжение T2_OUT
        // Задержка для устойчивого измерения вольтметром PV2 / XSC2
        for (j = 0; j < 100; j++)
            continue;
        delay(100);
    }

    while (1)
        ; // стоп: последний код (107) остаётся на выходе ЦАП
}
