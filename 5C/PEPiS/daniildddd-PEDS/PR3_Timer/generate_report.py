def p(text, bold=False, center=False, right=False, size=None):
    par = d.add_paragraph()
    if center:
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if right:
        par.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    par.paragraph_format.line_spacing = 1.5
    run = par.add_run(text)
    run.bold = bold
    run.font.name = "Times New Roman"
    run.font.size = Pt(size or 14)
    return par

def h1(text):
    h = d.add_heading(text, level=1)
    for r in h.runs:
        r.font.name = "Times New Roman"; r.font.size = Pt(16)
        r.font.color.rgb = RGBColor(0, 0, 0)
    h.paragraph_format.page_break_before = True
    return h

def h2(text):
    h = d.add_heading(text, level=2)
    for r in h.runs:
        r.font.name = "Times New Roman"; r.font.size = Pt(14)
    return h

def body(text):
    par = d.add_paragraph()
    par.paragraph_format.first_line_indent = Mm(12.5)
    par.paragraph_format.line_spacing = 1.5
    par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    run = par.add_run(text)
    run.font.name = "Times New Roman"; run.font.size = Pt(14)
    return par

def bullets(items):
    for it in items:
        par = d.add_paragraph(style="List Bullet")
        par.paragraph_format.line_spacing = 1.5
        run = par.add_run(it)
        run.font.name = "Times New Roman"; run.font.size = Pt(14)

def numbered(items):
    for it in items:
        par = d.add_paragraph(style="List Number")
        par.paragraph_format.line_spacing = 1.5
        run = par.add_run(it)
        run.font.name = "Times New Roman"; run.font.size = Pt(14)

def caption(text):
    # Подписи таблиц, слева без отступа (ГОСТ 7.32); подписи рисунков, отдельные p() по центру.
    par = d.add_paragraph()
    par.paragraph_format.line_spacing = 1.5
    run = par.add_run(text)
    run.font.name = "Times New Roman"; run.font.size = Pt(14)
    return par

def table(headers, rows, widths=None):
    t = d.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htxt in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        run = c.paragraphs[0].add_run(htxt)
        run.bold = True; run.font.name = "Times New Roman"; run.font.size = Pt(14)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(val))
            run.font.name = "Times New Roman"; run.font.size = Pt(14)
    return t

def code_block(text):
    for line in text.splitlines():
        par = d.add_paragraph()
        par.paragraph_format.space_after = Pt(0)
        par.paragraph_format.space_before = Pt(0)
        par.paragraph_format.line_spacing = 1.0
        run = par.add_run(line if line.strip() else " ")
        run.font.name = "Courier New"; run.font.size = Pt(11)

