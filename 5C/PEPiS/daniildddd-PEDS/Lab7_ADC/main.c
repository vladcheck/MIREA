#include <8051.h> // подключаем заголовочный файл (ТЗ, рис.60, Задание 2)

// Лабораторная №7, Задание 2: МК-51 + 8-битный АЦП (вариант 1: Vref+ = +2.5В, Vref- = -2.5В)
// P1 — вход (цифровой код с D0..D7 АЦП), P2 — выход (пробники X1..X8), P3.6 — строб SOC.

void main()
{
    unsigned char val; // переменная содержит цифровой код, отвечающий Uвх
    P1 = 0xFF; // инициализируем P1 на вход
    P2 = 0x00; // инициализируем P2 на выход
    P3_6 = 0;  // P3.6 — выход
    P3_6 = 1;  // начать преобразование (фронт SOC)
    val = P1;  // P1 содержит цифровой код
    P2 = val;  // включаем пробники (вывод кода на P2)
    while (1); // бесконечный цикл
}
