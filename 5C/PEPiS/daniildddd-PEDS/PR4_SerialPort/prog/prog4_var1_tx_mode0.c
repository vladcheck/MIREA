/*=====================================================================
 * ПР №4. Передача N=10 байт через последовательный порт МК-51, режим 0
 * Вариант 1 (таблица 12): T / K=0 (синхронный) / 1000 Кбит/с / XX=50h / N=10
 * Схема: Circuit4 (U1 P8051AH, XSC1 на P3.0, Y1 12 МГц)
 *
 * Режим 0: синхронный, 8 бит, f0 = fosc/12 = 1 МГц при кварце 12 МГц.
 * SCON = 0x00 (SM0=0,SM1=0, режим 0; SM2=0; REN=0, только передача).
 * Таймер Т/С1 и бит SMOD (PCON) в режиме 0 не влияют на скорость.
 * Метод: программно-управляемый (опрос TI). Прерывания (IE.4/вектор 23h)
 * для 8 мкс/байт избыточны.
 * Данные: массив tx[10] размещён как аналог резидентной памяти с 50h.
 * По окончании, P1.0 = 1 (LED D1 TX_DONE на схеме).
 * Компилятор: Keil C51 / SDCC (заголовок <8051.h> как в примере ТЗ).
 *====================================================================*/
#include <8051.h>          /* SFR: SBUF, SCON, TI, P1 и др. */

/* Передаваемые байты, аналог 50h..59h (тестовый счётчик 00h..09h,
 * на осциллографе XSC1 виден нарастающий код на P3.0). */
unsigned char xdata_at_50h_placeholder; /* адрес 50h занят данными (см. asm-вариант) */
static unsigned char tx[10] = {0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09};

/* Отправка одного байта в режиме 0: запись в SBUF запускает передачу,
 * аппаратный сдвиг, 8 бит за 8 машинных циклов, конец, флаг TI. */
void tput_mode0(unsigned char c1)
{
    TI = 0;        /* подготовить флаг (сбрасывается только программно) */
    SBUF = c1;     /* <-- СТАРТ: младший бит уходит первым на P3.0, синхро, на P3.1 */
    while (!TI)    /* ждать 8 мкс (при 12 МГц), опрос вместо прерывания */
        ;
    TI = 0;        /* подтвердить передачу */
}

void main(void)
{
    unsigned char i;
    SCON = 0x00;   /* режим 0, приём запрещён (REN=0), SM2=0 */
    P1_0 = 0;      /* LED погашен до начала */
    for (i = 0; i < 10; i++)   /* N=10 байт с условного адреса XX=50h */
    {
        tput_mode0(tx[i]);
    }
    P1_0 = 1;      /* готово: зажечь LED D1 (TX_DONE) */
    while (1)      /* бесконечный цикл (конец работы) */
        ;
}
