;=====================================================================
; ПР №4. Передача N=10 байт через последовательный порт МК-51, режим 0
; Вариант 1 (таблица 12): T / K=0 (синхронный) / 1000 Кбит/с / XX=50h / N=10
; Схема: Circuit4 (U1 P8051AH, XSC1 на P3.0, Y1 12 МГц)
;
; Режим 0: синхронный, кадр 8 бит данных без старт/стоп.
;   Данные, по RxD (P3.0), синхроимпульсы, по TxD (P3.1).
;   Скорость f0 = fosc/12 = 12 МГц/12 = 1 МГц (1000 Кбит/с),
;   1 бит за машинный цикл (1 мкс), байт, 8 мкс.
; Управление: SBUF (99h), буфер, SCON (98h) = 00h для передачи
;   (SM0=0,SM1=0, режим 0; SM2=0 обязателен; REN=0, приём закрыт;
;   TI, флаг конца передачи, сбрасывается программно).
; Метод: программно-управляемый (опрос TI), без прерываний.
;   Прерывания здесь избыточны: байт уходит за 8 мкс, опрос дешевле.
; Данные: 10 байт в резидентной памяти 50h..59h (инициализированы ниже
;   значениями 00h..09h как тестовый счётчик; в реальной задаче,
;   любые N байт пользователя с адреса XX).
; Индикация: по окончании, P1.0=1 (LED D1 TX_DONE на схеме).
;======================================================================
$MOD51                 ; подключение определений МК-51 (SFR, биты)

        ORG 00h
        JMP START        ; вектор сброса, на инициализацию

        ORG 40h          ; пользовательский код с 40h (30h занят данными примера ТЗ)
START:
        CLR TI           ; сброс флага передатчика (SCON.1)
        CLR RI           ; сброс флага приёмника (SCON.0), на всякий случай
        MOV SCON, #00h   ; режим 0: SM0=0,SM1=0; SM2=0; REN=0 (только передача)
        ; Таймер Т/С1 в режиме 0 НЕ используется, TMOD/TH1/PCON не трогаем.
        ; Кварц Y1 12 МГц уже даёт 1 МГц: дополнительно ничего считать не надо.

        MOV R0, #50h     ; R0, указатель на очередной байт (начало XX=50h)
        MOV R2, #10      ; R2, счётчик байт (N=10)

NEXT_BYTE:
        MOV A, @R0       ; взять очередной байт из резидентной памяти
        CLR TI           ; подготовить флаг (был сброшен прошлой итерацией)
        MOV SBUF, A      ; <-- СТАРТ передачи: запись в SBUF запускает сдвиг
        ; В режиме 0 сдвиг идёт сразу: младший бит, первым, синхро, на P3.1.
WAIT_TI:
        JNB TI, WAIT_TI  ; ждать конца передачи (TI установится аппаратно через 8 мкс)
        CLR TI           ; подтвердить: сбросить TI программно (аппаратно не сбрасывается!)
        INC R0           ; указатель на следующий байт (50h->51h...->59h)
        DJNZ R2, NEXT_BYTE ; цикл по всем 10 байтам

        SETB P1.0        ; индикация готовности: зажечь LED D1 (TX_DONE)
        SJMP $           ; бесконечный цикл (конец программы)
        ; Альтернатива с прерыванием (для справки, не используется):
        ;   MOV IE, #90h (EA=1,ES=1) + JMP на 23h, где обработчик делает CLR TI.
        ;   Здесь опрос TI проще и детерминированнее при 8 мкс/байт.

;---------------------------------------------------------------------
; Тестовые данные: 10 байт с адреса 50h (XX). Значения 00h..09h,
; удобны для осциллографа: видно нарастающий код на P3.0.
;---------------------------------------------------------------------
        ORG 50h
TXDATA: DB 00h, 01h, 02h, 03h, 04h, 05h, 06h, 07h, 08h, 09h

        END
