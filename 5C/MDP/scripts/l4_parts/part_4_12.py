    s -= (w4 ** 2 / 2) * (w1 * w2 + w1 * w3 + w2 * w3)
    s -= (w3 ** 3 / 6) * (w1 + w2)
    s -= w1 * w2 * w3 ** 2 / 2
    s -= w1 * w3 ** 2 / 3
