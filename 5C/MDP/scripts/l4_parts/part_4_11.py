rng = np.random.default_rng(42)
N = 200_000


def P_all_meet(n, q, N=N):
    # Вероятность того, что все n лиц встретятся (Монте-Карло).
    t = rng.random((N, n))
    return np.mean(np.max(t, axis=1) - np.min(t, axis=1) <= q)


qs = [0.2, 0.5, 0.8]
